"""Regenerate self-hosted CangEr WOFF2 subsets; requires fonttools[woff]."""
from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
DIRECTORY = ROOT / 'public/fonts'
SOURCE = DIRECTORY / 'cang-er-jin-kai.ttf'
UI_FILES = [
    'src/components/Intro.astro', 'src/components/Header.astro',
    'src/components/Footer.astro', 'src/components/DarkModeToggle.astro',
    'src/pages/index.astro', 'src/config.ts',
]


def ranges(points):
    values = sorted(points)
    groups = []
    start = end = values[0]
    for value in values[1:]:
        if value == end + 1:
            end = value
        else:
            groups.append((start, end))
            start = end = value
    groups.append((start, end))
    return ','.join(f'U+{start:X}' + (f'-{end:X}' if end != start else '') for start, end in groups)


def write_subset(filename, points):
    options = subset.Options()
    options.hinting = False
    font = TTFont(SOURCE, recalcTimestamp=False)
    sub = subset.Subsetter(options=options)
    sub.populate(unicodes=points)
    sub.subset(font)
    font.flavor = 'woff2'
    font.save(DIRECTORY / filename)
    font.close()
    return f'''@font-face {{
  font-family: "CangEr";
  font-style: normal;
  font-weight: 400;
  font-display: swap;
  src: url("/fonts/{filename}") format("woff2");
  unicode-range: {ranges(points)};
}}
'''


font = TTFont(SOURCE)
supported = set(font.getBestCmap())
font.close()
ui_text = ''.join((ROOT / filename).read_text() for filename in UI_FILES)
critical = (set(range(0x20, 0x7F)) | {ord(char) for char in ui_text if ord(char) > 127}) & supported
remaining = sorted(supported - critical)

# Preserve every codepoint without making any page download the complete TTF.
css = ['/* Generated by scripts/build-fonts.py. Font subsets have disjoint coverage. */\n']
css.append(write_subset('cang-er-jin-kai-ui.woff2', critical))
for index, start in enumerate(range(0, len(remaining), 256)):
    css.append(write_subset(f'cang-er-jin-kai-{index:03}.woff2', remaining[start:start + 256]))

for family, name in [('Source Serif Pro', 'source-serif-pro'), ('JetBrains Mono', 'jetbrains-mono')]:
    for weight in [400, 600]:
        css.append(f'''@font-face {{
  font-family: "{family}";
  font-style: normal;
  font-weight: {weight};
  font-display: swap;
  src: url("/fonts/{name}-latin-{weight}-normal.woff2") format("woff2");
  unicode-range: U+0-FF,U+131,U+152-153,U+2BB-2BC,U+2C6,U+2DA,U+2DC,U+304,U+308,U+329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD;
}}
''')
(DIRECTORY / 'inkrain.css').write_text('\n'.join(css))
print({'original_bytes': SOURCE.stat().st_size, 'supported_codepoints': len(supported),
       'ui_codepoints': len(critical), 'ui_bytes': (DIRECTORY / 'cang-er-jin-kai-ui.woff2').stat().st_size,
       'additional_subsets': (len(remaining) + 255) // 256})
