CREATE TABLE IF NOT EXISTS blog_users (
 id VARCHAR(36) PRIMARY KEY, email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, created_at DATETIME(3) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS blog_sessions (
 token_hash VARCHAR(64) PRIMARY KEY, user_id VARCHAR(36) NOT NULL, expires_at DATETIME(3) NOT NULL,
 FOREIGN KEY (user_id) REFERENCES blog_users(id) ON DELETE CASCADE, INDEX (expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS blog_login_attempts (
 attempt_key VARCHAR(64) PRIMARY KEY, count INT NOT NULL, resets_at DATETIME(3) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS blog_categories (id VARCHAR(36) PRIMARY KEY, name VARCHAR(100) NOT NULL UNIQUE)
 ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS blog_tags (id VARCHAR(36) PRIMARY KEY, name VARCHAR(100) NOT NULL UNIQUE)
 ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS blog_posts (
 id VARCHAR(36) PRIMARY KEY, section VARCHAR(20) NOT NULL, year VARCHAR(4) NOT NULL, slug VARCHAR(180) NOT NULL,
 path VARCHAR(512) NOT NULL UNIQUE, title VARCHAR(255) NOT NULL, markdown LONGTEXT NOT NULL, description TEXT NOT NULL,
 category_id VARCHAR(36), author_id VARCHAR(36) NOT NULL, status VARCHAR(16) NOT NULL, featured BOOLEAN NOT NULL DEFAULT FALSE,
 external_url TEXT NOT NULL, cover_url TEXT NOT NULL, canonical_url TEXT NOT NULL, metadata JSON NOT NULL,
 published_at DATETIME(3) NOT NULL, content_updated_at DATETIME(3), created_at DATETIME(3) NOT NULL, updated_at DATETIME(3) NOT NULL,
 version INT NOT NULL DEFAULT 1, source_path VARCHAR(512) UNIQUE,
 FOREIGN KEY (category_id) REFERENCES blog_categories(id) ON DELETE SET NULL,
 FOREIGN KEY (author_id) REFERENCES blog_users(id), INDEX blog_posts_public (status, section, published_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS blog_post_tags (
 post_id VARCHAR(36) NOT NULL, tag_id VARCHAR(36) NOT NULL, PRIMARY KEY (post_id, tag_id),
 FOREIGN KEY (post_id) REFERENCES blog_posts(id) ON DELETE CASCADE, FOREIGN KEY (tag_id) REFERENCES blog_tags(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS blog_post_drafts (
 post_id VARCHAR(36) PRIMARY KEY, content JSON NOT NULL, updated_at DATETIME(3) NOT NULL,
 FOREIGN KEY (post_id) REFERENCES blog_posts(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS blog_post_revisions (
 id VARCHAR(36) PRIMARY KEY, post_id VARCHAR(36) NOT NULL, content JSON NOT NULL, action VARCHAR(24) NOT NULL, created_at DATETIME(3) NOT NULL,
 FOREIGN KEY (post_id) REFERENCES blog_posts(id) ON DELETE CASCADE, INDEX (post_id, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS blog_redirects (
 path VARCHAR(512) PRIMARY KEY, post_id VARCHAR(36) NOT NULL,
 FOREIGN KEY (post_id) REFERENCES blog_posts(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS blog_media (
 id VARCHAR(36) PRIMARY KEY, name VARCHAR(255) NOT NULL, storage_key VARCHAR(512) NOT NULL, url TEXT NOT NULL,
 mime VARCHAR(100) NOT NULL, size INT NOT NULL, checksum VARCHAR(64) NOT NULL UNIQUE, sha VARCHAR(64),
 alt VARCHAR(500) NOT NULL DEFAULT '', status VARCHAR(16) NOT NULL, created_at DATETIME(3) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
